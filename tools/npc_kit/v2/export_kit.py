"""export_kit.py — turns an approved study character into what the Studio side needs:

  * an Import 3D batch (one GLB, one node per piece, named "<batch>__<piece>") written
    through the forge's own write_glb, plus pieces.json for the harness renderer;
  * a GENERATED Lua shell manifest, ReplicatedStorage/Modules/NpcKit/NpcShells/<Id>.lua,
    that NpcForge assembles from: per piece the bone, whether it IS the bone's visible
    MeshPart (slot) or hangs off it (welded), the mesh's bounding-box centre in bone space
    (Roblox's importer centres every MeshPart on its own bbox, so this is the offset that
    puts the mesh back where it was authored), the bbox size, triangles, colour, ownership.

Every piece is exported in its BONE's local frame (props are converted from their posed
world placement into hand space), so the manifest needs no rotations — a translation per
piece and the rig's own Motor6Ds do the rest.

    cd tools && python -m npc_kit.v2.export_kit          # Gianluca V2.5
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

from brainrot_forge.export_glb import write_glb

from npc_kit.v2 import characters25 as C
from npc_kit.v2 import lowpoly as L
from npc_kit.v2 import profiles as P
from npc_kit.v2.kit import Character, Piece

HERE = Path(__file__).resolve().parent
TOOLS = HERE.parents[1]
REPO = TOOLS.parent
KIT = REPO / "game-src" / "npc-kit"
SHELLS_DIR = KIT / "ReplicatedStorage" / "Modules" / "NpcKit" / "NpcShells"
OUT = TOOLS / "out" / "npc_v25_kit"

KIND_OF_CATEGORY = {"body": "body", "face": "face", "hair": "hair", "hat": "hair", "outfit": "outfit", "accessory": "outfit", "prop": "prop"}


def bone_local(piece: Piece, bones: dict[str, P.Bone]) -> L.Mesh:
    """World-placed props come back into their bone's frame; everything else already is."""
    if not piece.world:
        return piece.mesh
    b = bones[piece.bone]
    return piece.mesh.transformed(M=b.M.T, p=None).transformed(p=-(b.M.T @ b.p))


def manifest_for(ch: Character) -> dict:
    bones = P.pose(ch.profile, ch.rest)
    pieces = []
    for p in ch.pieces:
        m = bone_local(p, bones)
        lo, hi = m.bounds()
        centre = (lo + hi) / 2
        size = hi - lo
        row = {
            "name": p.name, "bone": p.bone, "slot": bool(p.slot), "kind": KIND_OF_CATEGORY.get(p.category, "outfit"),
            "offset": [round(float(v), 4) for v in centre], "size": [round(float(v), 4) for v in size],
            "tris": int(p.tris), "color": list(p.mesh.color), "bespoke": p.ownership == "specific",
        }
        if p.category == "prop":
            row["grip"] = p.bone
            if p.name == "Spear" or p.name == "Cane" or p.name == "Sword":
                row["planted"] = True
        pieces.append(row)
    base_sizes = {name: [round(float(v), 4) for v in ch.profile.size(name)] for name in ch.profile.parts if name != "HumanoidRootPart"}
    return {"id": ch.id, "batch": ch.id, "profile": ch.profile.id.lower(), "version": 1, "tier": ch.tier,
            "headOffset": round(ch.profile.head_offset, 4), "height": round(ch.profile.height, 4),
            "baseSizes": base_sizes, "pieces": pieces,
            "rest": ch.rest}


def write_glb_batch(ch: Character, out_dir: Path) -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    bones = P.pose(ch.profile, ch.rest)

    class _M:
        name = ch.id
        palette = {}

    roles = {}
    render = {}
    for p in ch.pieces:
        m = bone_local(p, bones)
        _M.palette[p.name] = "#%02x%02x%02x" % p.mesh.color
        roles[p.name] = m.to_forge_mesh(p.name)
        lo, hi = m.bounds()
        centre = (lo + hi) / 2
        render[p.name] = {"positions": (m.verts - centre).round(4).tolist(), "indices": m.faces.tolist(), "size": (hi - lo).round(4).tolist()}
    path = out_dir / f"{ch.id}.glb"
    write_glb(path, [(_M, roles)])
    (out_dir / f"{ch.id}.pieces.json").write_text(json.dumps(render))
    return {"glb": str(path), "nodes": len(roles), "bytes": path.stat().st_size}


def lua_vec(v) -> str:
    return "V(%.4f, %.4f, %.4f)" % tuple(v)


def write_lua_manifest(man: dict, path: Path) -> None:
    lines = [
        f"-- NpcShells/{man['id']} -- GENERATED by tools/npc_kit/v2/export_kit.py from the approved V2.5 study.",
        "-- Do not hand-edit: re-run the exporter. Every offset is the mesh's bounding-box centre in its",
        "-- BONE's space (Roblox's Import 3D centres a MeshPart on its bbox); `slot` pieces ARE the bone's",
        "-- visible MeshPart, the rest weld to the bone. Sizes are for the base profile; NpcForge scales",
        "-- them per bone when a recipe carries bodyOverrides (D-22).",
        "",
        "local function V(x, y, z) return Vector3.new(x, y, z) end",
        "local function C(r, g, b) return Color3.fromRGB(r, g, b) end",
        "",
        "return {",
        f"\tid = \"{man['id']}\", batch = \"{man['batch']}\", profile = \"{man['profile']}\", version = {man['version']}, tier = {man['tier']},",
        f"\theadOffset = {man['headOffset']:.4f}, height = {man['height']:.4f},",
        "\tbaseSizes = {",
    ]
    for name, s in man["baseSizes"].items():
        lines.append(f"\t\t{name} = {lua_vec(s)},")
    lines.append("\t},")
    lines.append("\tpieces = {")
    for p in man["pieces"]:
        extra = ""
        if p.get("grip"):
            extra += f", grip = \"{p['grip']}\""
        if p.get("planted"):
            extra += ", planted = true"
        lines.append(
            f"\t\t{{ name = \"{p['name']}\", bone = \"{p['bone']}\", slot = {'true' if p['slot'] else 'false'}, kind = \"{p['kind']}\", "
            f"offset = {lua_vec(p['offset'])}, size = {lua_vec(p['size'])}, tris = {p['tris']}, color = C({p['color'][0]}, {p['color'][1]}, {p['color'][2]}), "
            f"bespoke = {'true' if p['bespoke'] else 'false'}{extra} }},")
    lines.append("\t},")
    lines.append("}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def export(ch: Character) -> dict:
    man = manifest_for(ch)
    glb = write_glb_batch(ch, OUT)
    (OUT / f"{ch.id}.manifest.json").write_text(json.dumps(man, indent=1))
    write_lua_manifest(man, SHELLS_DIR / f"{ch.id}.lua")
    return {"manifest": man, "glb": glb, "lua": str(SHELLS_DIR / f"{ch.id}.lua")}


def study_character() -> Character:
    """The approved character with the face in its EXPORT rest (no expression baked into the
    mesh: NpcFaceConfig applies the eight states as deltas at build / run time)."""
    return C.gianluca_v25(expression="rest")


def main() -> int:
    ch = study_character()
    res = export(ch)
    m = res["manifest"]
    print(f"{m['id']}: {len(m['pieces'])} pieces, {sum(p['tris'] for p in m['pieces'])} tris, "
          f"{sum(1 for p in m['pieces'] if p['bespoke'])} bespoke, profile {m['profile']}, head offset {m['headOffset']}")
    print("glb", res["glb"])
    print("lua", res["lua"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
